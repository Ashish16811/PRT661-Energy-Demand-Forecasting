# 5. Equivalence checks
# ---------------------------------------------------------------------------

def equivalence_checks() -> list[tuple[str, bool]]:
    checks = [("contract constants match pipeline", not check_constants(edp)),
              ("full GRU parameters equal pipeline", gru_parameters() == edp.GRU_PARAMETERS["full"]),
              ("quick GRU parameters equal pipeline", gru_parameters(True) == edp.GRU_PARAMETERS["quick"])]
    starts = np.arange(700, 30000 - BLOCK + 1, 12)
    tr, va = split_train_validation(starts, 30000)
    val_pos = 30000 - edp.NEURAL_VALIDATION_DAYS * 48
    checks.append(("validation = last 56 days, no straddling sequence",
                   bool((tr + BLOCK <= val_pos).all() and (va >= val_pos).all())))
    idx = pd.date_range("2024-01-01", periods=5000, freq="30min")
    y = np.random.default_rng(2).normal(1000, 50, 5000)
    y[4000:] = np.nan
    b = fit_gru_scalers(y, np.random.default_rng(3).normal(size=(5000, 3)), 3500, idx, ["a", "b", "c"])
    checks.append(("scalers fitted before the limit only", b.fitted_until == idx[3499] and b.fitted_rows == 3500))
    # provenance on a synthetic panel
    gidx = pd.date_range("2025-01-01", periods=200, freq="30min")
    known = pd.DataFrame({"weather_feature_source": "BACKTEST_CLIMATOLOGY",
                          "weather_information_origin": gidx[100]}, index=gidx[100:])
    panel = edp.Panel(index=gidx, y=np.r_[np.ones(100), np.full(100, np.nan)], actual=np.ones(200),
                      origin_pos=100, grid_pos=np.arange(100, 200), known=known,
                      train_rows=pd.DataFrame(), train_pos=np.arange(100))
    maps = edp.OriginMaps(gidx[100], {}, None, None, None, 100, gidx[99], "2025")
    checks.append(("weather provenance check passes on climatology rows",
                   validate_weather_provenance(panel)["only_expected_source"]))
    checks.append(("information boundary check passes", validate_information_boundary(panel, maps)["PASS"]))
    bad = edp.Panel(index=gidx, y=np.ones(200), actual=np.ones(200), origin_pos=100,
                    grid_pos=np.arange(100, 200), known=known.assign(TOTALDEMAND=1.0),
                    train_rows=pd.DataFrame(), train_pos=np.arange(100))
    checks.append(("information boundary check catches leaked target/actuals",
                   not validate_information_boundary(bad, maps)["PASS"]))
    if edp.tf_status()["available"]:
        tf = edp.get_tf()
        for mode, look in (("full", 336), ("full", 672), ("quick", 336)):
            p = edp.GRU_PARAMETERS[mode]
            same = (build_gru_network(tf, look, 6, 41, p).count_params()
                    == edp._build_gru(tf, look, 6, 41, p).count_params())
            checks.append((f"{mode} architecture parameter count equals pipeline (L={look})", same))
        # identical seeds -> identical trained weights (module vs pipeline building blocks)
        p = dict(gru_parameters(True), gru_units=8, dense_units=8, epochs=2, batch_size=32)
        rng = np.random.default_rng(5)
        mk = lambda n, s0: SequenceBatch(rng.normal(size=(n, 48, 2)).astype(np.float32),
                                         rng.normal(size=(n, 48, 3)).astype(np.float32),
                                         rng.normal(size=(n, 48)).astype(np.float32),
                                         np.arange(s0, s0 + n), 48, 10_000)
        tr_b, va_b = mk(64, 100), mk(16, 400)
        net1, _, best1, _ = train_gru(tf, tr_b, va_b, p, 17, "module")
        tf.keras.backend.clear_session()
        edp.set_global_seeds(17)
        net2 = edp._build_gru(tf, 48, 2, 3, p)
        cbs, _ = edp._keras_callbacks(tf, p, "pipeline", with_validation=True)
        net2.fit([tr_b.encoder, tr_b.decoder], tr_b.target, validation_data=([va_b.encoder, va_b.decoder], va_b.target),
                 epochs=p["epochs"], batch_size=p["batch_size"], shuffle=True, verbose=0, callbacks=cbs)
        w_same = all(np.allclose(a, b, atol=1e-5) for a, b in zip(net1.get_weights(), net2.get_weights()))
        checks.append(("identical seed -> identical trained weights (module vs pipeline)", w_same))
    return checks


def main() -> int:
    res = equivalence_checks()
    for name, ok in res:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    bad = sum(not ok for _, ok in res)
    print(f"GRU training/provenance equivalence: {len(res) - bad}/{len(res)} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
