def recompute_from_detail(detail: pd.DataFrame, model: str = MODEL) -> pd.DataFrame:
    """Recompute region x origin metrics from all_models_backtest_detail with the
    pipeline's own group_metrics(), for comparison with model_comparison_by_year."""
    d = detail[detail["model"] == model]
    return edp.group_metrics(d, ["region", "model", "backtest_year"])


def compare_with_published(recomputed: pd.DataFrame, by_year: pd.DataFrame,
                           cols=("MAE", "RMSE", "nMAE_pct", "Bias")) -> pd.DataFrame:
    pub = by_year[by_year["status"].isin(OK)]
    j = recomputed.merge(pub, on=["region", "model", "backtest_year"], suffixes=("_recomputed", "_published"))
    for c in cols:
        j[f"{c}_abs_diff"] = (j[f"{c}_recomputed"] - j[f"{c}_published"]).abs()
    return j[["region", "model", "backtest_year"] + [f"{c}_abs_diff" for c in cols]]


