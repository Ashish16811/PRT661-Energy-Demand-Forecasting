# 5. Equivalence and leakage checks
# ---------------------------------------------------------------------------

def equivalence_checks() -> list[tuple[str, bool]]:
    checks = [("contract constants match pipeline", not check_constants(edp)),
              ("decoder features equal pipeline (41, no demand-derived)",
               DECODER_FEATURES == list(edp.GRU_DECODER_FEATURES) and not set(DECODER_FEATURES) & edp.DEMAND_FEATURES),
              ("primary lookback 336 / sensitivity 672",
               SequenceSpec.primary().lookback == 336 and SequenceSpec.sensitivity().lookback == 672),
              ("GRU_L672 is sensitivity-only", not SequenceSpec.sensitivity().competes_in_selection)]
    y = np.arange(9000, dtype=float)
    opos = 8000
    y[opos:] = np.nan
    y[3000] = np.nan
    for spec in (SequenceSpec.primary(), SequenceSpec.sensitivity(), SequenceSpec.primary(quick=True)):
        a = training_starts(y, opos, spec)
        b = edp.gru_training_starts(y, opos, spec.lookback, spec.stride)
        checks.append((f"training starts identical to pipeline (L={spec.lookback}, stride={spec.stride})",
                       np.array_equal(a, b)))
        checks.append((f"windows containing the gap are skipped (L={spec.lookback})",
                       not any(s - spec.lookback <= 3000 < s + BLOCK for s in a)))
    spec = SequenceSpec.primary()
    starts = training_starts(y, opos, spec)[:20]
    ys = np.nan_to_num(y)
    Ecal = np.zeros((len(y), len(edp.GRU_ENCODER_CALENDAR)), np.float32)
    Dm = np.random.default_rng(1).normal(size=(len(y), 3)).astype(np.float32)
    batch = build_sequence_batch(ys, Ecal, Dm, starts, spec, opos)
    ref = edp.build_gru_arrays(ys, Ecal, Dm, starts, spec.lookback)
    checks.append(("sequence arrays identical to pipeline",
                   all(np.array_equal(p, q) for p, q in zip((batch.encoder, batch.decoder, batch.target), ref))))
    checks.append(("encoder ends at s-1, target starts at s",
                   bool(np.allclose(batch.encoder[:, -1, 0], starts - 1) and np.allclose(batch.target[:, 0], starts))))
    # recursion never exposes a horizon actual: plant a sentinel in the actuals
    actual = np.full(3000, 500.0)
    actual[2000:] = 1e9                        # would be obvious if it leaked
    st = RecursiveSequenceState(actual, 2000, 336)
    grid = np.arange(2000, 2000 + 5 * BLOCK)

    class Identity:
        def transform(self, v):
            return np.asarray(v, float)

        def inverse(self, z):
            return np.asarray(z, float)
    seen = []

    def fake_block(enc, dec):
        seen.append(float(np.max(enc[0, :, 0])))
        return np.full(BLOCK, 510.0)
    recursive_forecast(fake_block, st, grid, np.zeros((3000, 5)), np.zeros((3000, 2)), Identity())
    prov = st.provenance()
    checks.append(("no horizon actual ever enters an encoder window", max(seen) < 1e6))
    checks.append(("provenance: block 1 all actual, later blocks include predictions",
                   st.log[0]["predicted_steps"] == 0 and st.log[1]["predicted_steps"] == BLOCK
                   and prov["actual_encoder_steps"] + prov["predicted_encoder_steps"] == 5 * 336))
    return checks


def main() -> int:
    res = equivalence_checks()
    for name, ok in res:
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    bad = sum(not ok for _, ok in res)
    print(f"GRU sequence engine equivalence: {len(res) - bad}/{len(res)} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
