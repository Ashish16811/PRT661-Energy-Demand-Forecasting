REQUIRED = {
    "by_year": "metrics/model_comparison_by_year.csv",
    "by_region": "metrics/model_comparison_by_region.csv",
    "by_horizon": "metrics/model_comparison_by_horizon.csv",
    "stability": "metrics/model_stability.csv",
    "peak": "metrics/peak_demand_metrics.csv",
    "residual": "metrics/residual_analysis.csv",
    "neural_vs_previous": "metrics/neural_vs_previous_comparison.csv",
    "history": "metrics/neural_training_history.csv",
}


def load_results(results_dir: str | Path) -> dict[str, pd.DataFrame]:
    """Load the CSVs this validation needs; a missing file is an explicit error."""
    root = Path(results_dir)
    out, missing = {}, []
    for key, rel in REQUIRED.items():
        p = root / rel
        if p.exists():
            out[key] = pd.read_csv(p)
        else:
            missing.append(rel)
    if missing:
        raise FileNotFoundError(f"evidence files missing: {missing}")
    return out


