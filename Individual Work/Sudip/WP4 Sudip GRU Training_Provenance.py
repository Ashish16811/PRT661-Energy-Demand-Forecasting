# 4. Weather / context provenance and information-boundary validation
# ---------------------------------------------------------------------------

def validate_weather_provenance(panel, mode: str = "historical_backtest") -> dict:
    """Every horizon row must carry origin-safe climatology, never realised weather."""
    k = panel.known
    expected = "BACKTEST_CLIMATOLOGY" if mode == "historical_backtest" else "PRODUCTION_CLIMATOLOGY"
    src = sorted(set(k.get("weather_feature_source", pd.Series(dtype=str)).astype(str)))
    info = pd.to_datetime(k.get("weather_information_origin", pd.Series(dtype="datetime64[ns]")))
    origin = panel.index[panel.origin_pos]
    return {"sources": src, "only_expected_source": src == [expected],
            "information_origin_is_forecast_origin": bool(len(info) and (info == origin).all())}


def validate_information_boundary(panel, maps, scalers: NeuralScalerBundle | None = None) -> dict:
    origin = panel.index[panel.origin_pos]
    res = {
        "history_ends_before_origin": bool(maps.history_end is not None and maps.history_end < origin),
        "target_hidden_from_horizon_rows": not any(c in panel.known.columns for c in edp.HORIZON_HIDDEN_COLUMNS),
        "no_actual_demand_after_origin": bool(np.isnan(panel.y[panel.origin_pos:]).all()),
    }
    if scalers is not None:
        try:
            scalers.assert_before(origin)
            res["scalers_fitted_before_origin"] = True
        except AssertionError:
            res["scalers_fitted_before_origin"] = False
    res["PASS"] = all(v for v in res.values())
    return res


