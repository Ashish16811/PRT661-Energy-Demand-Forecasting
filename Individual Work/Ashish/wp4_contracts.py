from __future__ import annotations

import importlib.util
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

PIPELINE_FILENAME = "Energy_Demand_Forecasting_Pipeline.py"
EXPECTED_PIPELINE_VERSION = "4.0.0"      # the version that produced the WP4 results

# Contract constants. They duplicate nothing: check_constants() proves they are
# identical to the pipeline's own values before any module is merged.
TIME = "SETTLEMENTDATE"
TARGET = "TOTALDEMAND"
FREQ = "30min"
INTERVALS_PER_DAY = 48
BLOCK = 48
REGIONS = ["NSW1", "QLD1", "VIC1", "SA1", "TAS1", "WA"]
RANDOM_SEED = 20260914

_PIPELINE = None


def load_pipeline(path: str | os.PathLike | None = None):
    """Import the integrated pipeline once (it never runs on import).

    Search order: explicit path -> $WP4_PIPELINE_PATH -> this folder -> parent folder
    -> ../Pipeline/.
    """
    global _PIPELINE
    if _PIPELINE is not None and path is None:
        return _PIPELINE
    here = Path(__file__).resolve().parent
    candidates = [Path(path)] if path else []
    if os.environ.get("WP4_PIPELINE_PATH"):
        candidates.append(Path(os.environ["WP4_PIPELINE_PATH"]))
    candidates += [here / PIPELINE_FILENAME, here.parent / PIPELINE_FILENAME,
                   here.parent / "Pipeline" / PIPELINE_FILENAME]
    for c in candidates:
        if c.is_file():
            spec = importlib.util.spec_from_file_location("energy_pipeline_v4", c)
            mod = importlib.util.module_from_spec(spec)
            sys.modules["energy_pipeline_v4"] = mod
            spec.loader.exec_module(mod)
            _PIPELINE = mod
            return mod
    raise FileNotFoundError(f"{PIPELINE_FILENAME} not found; set WP4_PIPELINE_PATH")


def check_constants(edp=None) -> list[str]:
    """Return a list of mismatches between this contract and the pipeline (empty = OK)."""
    edp = edp or load_pipeline()
    problems = []
    for name, value in (("TIME", TIME), ("TARGET", TARGET), ("FREQ", FREQ),
                        ("INTERVALS_PER_DAY", INTERVALS_PER_DAY), ("BLOCK", BLOCK),
                        ("REGIONS", REGIONS), ("RANDOM_SEED", RANDOM_SEED),
                        ("PIPELINE_VERSION", EXPECTED_PIPELINE_VERSION)):
        if getattr(edp, name) != value:
            problems.append(f"{name}: contract={value!r} pipeline={getattr(edp, name)!r}")
    return problems


