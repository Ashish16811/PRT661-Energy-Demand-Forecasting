# 2. Learning-curve validation
# ---------------------------------------------------------------------------

def learning_curve_summary(history: pd.DataFrame, model: str = MODEL,
                           epoch_limit: int | None = None) -> pd.DataFrame:
    """One row per region x origin for the early-stopping fit.

    Classification rules (declared, not tuned to the result):
      EPOCH_LIMIT_REACHED - best epoch == last epoch == configured limit (may be under-trained)
      OVERFITTING_SIGNAL  - final val loss > 1.10 x best val loss while train loss fell
      CONVERGED           - otherwise (early stopping ended the fit near a minimum)
    """
    params = edp.MLP_PARAMETERS["full"] if model == "MLP" else edp.GRU_PARAMETERS["full"]
    limit = epoch_limit or params["epochs"]
    h = history[(history["model"] == model) & (history["phase"] == "early_stopping_fit")]
    rows = []
    for (region, origin), g in h.groupby(["region", "backtest_origin"]):
        g = g.sort_values("epoch")
        TrainingHistory(region, model, pd.Timestamp(origin), g).validate()
        ib = g["val_loss"].idxmin()
        best_ep, last_ep = int(g.loc[ib, "epoch"]), int(g["epoch"].max())
        min_val, final_val = float(g.loc[ib, "val_loss"]), float(g["val_loss"].iloc[-1])
        train_best, train_final = float(g.loc[ib, "loss"]), float(g["loss"].iloc[-1])
        if best_ep == last_ep == limit:
            verdict = "EPOCH_LIMIT_REACHED"
        elif final_val > 1.10 * min_val and train_final < train_best:
            verdict = "OVERFITTING_SIGNAL"
        else:
            verdict = "CONVERGED"
        rows.append({"region": region, "model": model, "backtest_origin": origin,
                     "epochs_run": last_ep, "best_epoch": best_ep, "min_val_loss": min_val,
                     "train_loss_at_best": train_best, "generalisation_gap": min_val - train_best,
                     "final_val_loss": final_val, "final_learning_rate": float(g["learning_rate"].iloc[-1]),
                     "verdict": verdict})
    return pd.DataFrame(rows)


def plot_learning_curves(history: pd.DataFrame, out_png: Path, model: str = MODEL) -> Path:
    """Re-draw N01 from neural_training_history.csv (independent of the pipeline plot code)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    h = history[(history["model"] == model) & (history["phase"] == "early_stopping_fit")]
    regions = sorted(h["region"].unique())
    fig, axes = plt.subplots(2, 3, figsize=(14, 7), squeeze=False)
    for ax, r in zip(axes.ravel(), regions):
        g = h[h["region"] == r]
        for i, (o, go) in enumerate(g.groupby("backtest_origin")):
            c = plt.cm.viridis(i / max(1, g["backtest_origin"].nunique() - 1))
            ax.plot(go["epoch"], go["loss"], color=c, lw=1, label=f"{str(o)[:4]} train")
            ax.plot(go["epoch"], go["val_loss"], color=c, lw=1, ls="--", label=f"{str(o)[:4]} val")
        ax.set_title(r); ax.set_xlabel("epoch"); ax.set_ylabel("Huber loss (scaled)")
    for ax in axes.ravel()[len(regions):]:
        ax.axis("off")
    axes[0, 0].legend(fontsize=6, ncol=2)
    fig.suptitle(f"{model} - training vs validation loss (independent re-plot)")
    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=140)
    plt.close(fig)
    return out_png


