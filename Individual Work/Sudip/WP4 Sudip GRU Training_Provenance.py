# ---------------------------------------------------------------------------
# 1. Configuration and architecture
# ---------------------------------------------------------------------------

def gru_parameters(quick: bool = False) -> dict:
    return copy.deepcopy(edp.GRU_PARAMETERS["quick" if quick else "full"])


def build_gru_network(tf, lookback: int, n_encoder: int, n_decoder: int, p: dict):
    """Encoder GRU over the lookback window -> dropout -> repeated for the 48 steps ->
    concatenated with each step's known-future features -> Dense(ReLU) -> Dense(1).

    Plain GRU settings (tanh/sigmoid, no recurrent_dropout) keep the cuDNN kernel
    eligible on a GPU; dropout is applied as separate layers."""
    L = tf.keras.layers
    enc_in = tf.keras.Input(shape=(lookback, n_encoder), name="history_sequence")
    dec_in = tf.keras.Input(shape=(BLOCK, n_decoder), name="known_future_block")
    ctx = L.GRU(p["gru_units"], name="gru_encoder")(enc_in)
    ctx = L.Dropout(p["dropout"])(ctx)
    rep = L.RepeatVector(BLOCK)(ctx)
    h = L.Concatenate(axis=-1)([rep, dec_in])
    h = L.Dense(p["dense_units"], activation="relu", name="per_step_dense")(h)
    h = L.Dropout(p["dropout"])(h)
    out = L.Dense(1, activation="linear", name="demand_scaled")(h)
    out = L.Reshape((BLOCK,))(out)
    net = tf.keras.Model([enc_in, dec_in], out, name="GRU_day_block_forecaster")
    net.compile(optimizer=tf.keras.optimizers.Adam(p["learning_rate"]),
                loss=tf.keras.losses.Huber(delta=edp.HUBER_DELTA), metrics=["mae"])
    return net


# ---------------------------------------------------------------------------
# 2. Validation period and scaling (information boundary)
# ---------------------------------------------------------------------------

def split_train_validation(starts: np.ndarray, origin_pos: int) -> tuple[np.ndarray, np.ndarray]:
    """Validation = sequences whose block starts in the last NEURAL_VALIDATION_DAYS before
    the origin; training sequences must END before that block (no straddling). If the
    history is too short the last 10% of sequences is used instead (pipeline rule)."""
    val_pos = origin_pos - edp.NEURAL_VALIDATION_DAYS * edp.INTERVALS_PER_DAY
    tr = starts[starts + BLOCK <= val_pos]
    va = starts[starts >= val_pos]
    if len(va) < 10 or len(tr) < 100:
        cut = int(len(starts) * 0.9)
        tr, va = starts[:cut], starts[cut:]
    if len(va) and len(tr):
        assert int(tr.max()) < int(va.min()), "validation sequences must follow training sequences"
    assert (va + BLOCK <= origin_pos).all(), "validation reaches the forecast horizon"
    return tr, va


def fit_gru_scalers(y: np.ndarray, D: np.ndarray, limit: int, index: pd.DatetimeIndex,
                    decoder_features: list) -> NeuralScalerBundle:
    """Target scaler on demand before `limit`; decoder scaler on known-future rows before
    `limit`. `limit` is the end of the training sequences (early-stopping fit) or the
    origin (refit) - never beyond it."""
    ts = edp.TargetScaler().fit(y[:limit])
    ds = edp.ColumnScaler(decoder_features).fit(D[:limit])
    return NeuralScalerBundle(ds, ts, fitted_until=index[limit - 1], fitted_rows=int(limit))


# ---------------------------------------------------------------------------
# 3. Training controls
# ---------------------------------------------------------------------------

def train_gru(tf, train: SequenceBatch, val: SequenceBatch, p: dict, seed: int, label: str):
    """Early-stopped fit. Returns (net, history_frame, best_epoch, lr_path)."""
    train.validate()
    val.validate()
    tf.keras.backend.clear_session()
    edp.set_global_seeds(seed)
    net = build_gru_network(tf, train.lookback, train.encoder.shape[2], train.decoder.shape[2], p)
    cbs, rec = edp._keras_callbacks(tf, p, label, with_validation=True)
    net.fit([train.encoder, train.decoder], train.target,
            validation_data=([val.encoder, val.decoder], val.target),
            epochs=p["epochs"], batch_size=p["batch_size"], shuffle=True, verbose=0, callbacks=cbs)
    edp.check_cancel()
    best, lr_path = edp._best_epoch(rec)
    return net, edp._history_frame(rec, "early_stopping_fit"), best, lr_path


def refit_gru(tf, full: SequenceBatch, p: dict, seed: int, best_epoch: int, lr_path: list, label: str):
    """Refit on every pre-origin sequence for the early-stopped epoch count, replaying the
    learning-rate path (no validation data exists at this stage)."""
    full.validate()
    tf.keras.backend.clear_session()
    edp.set_global_seeds(seed)
    net = build_gru_network(tf, full.lookback, full.encoder.shape[2], full.decoder.shape[2], p)
    cbs, rec = edp._keras_callbacks(tf, p, label + " refit", with_validation=False, lr_replay=lr_path)
    net.fit([full.encoder, full.decoder], full.target, epochs=max(1, best_epoch),
            batch_size=p["batch_size"], shuffle=True, verbose=0, callbacks=cbs)
    edp.check_cancel()
    return net, edp._history_frame(rec, "refit_full_history")


def learning_history(region: str, model: str, origin, frames: list, best_epoch) -> TrainingHistory:
    th = TrainingHistory(region, model, pd.Timestamp(origin), pd.concat(frames, ignore_index=True), best_epoch)
    th.validate()
    return th


def convergence_flags(history: pd.DataFrame, epoch_limit: int) -> dict:
    """Declared diagnostics for the report (not used for selection)."""
    e = history[history["phase"] == "early_stopping_fit"]
    if e.empty:
        return {"status": "NO_HISTORY"}
    best = int(e.loc[e["val_loss"].idxmin(), "epoch"])
    return {"epochs_run": int(e["epoch"].max()), "best_epoch": best,
            "hit_epoch_limit": bool(best == int(e["epoch"].max()) == epoch_limit),
            "lr_reduced": bool(e["learning_rate"].min() < e["learning_rate"].max())}


def capture_failure(region: str, model: str, origin, stage: str, exc: BaseException) -> dict:
    """Row in the model_failures.csv format - a failure is recorded, never hidden."""
    return {"region": region, "model": model, "backtest_origin": origin, "stage": stage,
            "error_message": f"{type(exc).__name__}: {exc}"[:2000], "exception_type": type(exc).__name__,
            "traceback_tail": "".join(traceback.format_exception(type(exc), exc, exc.__traceback__))[-1500:],
            "recorded_at": datetime.now().isoformat(timespec="seconds"), "status": "MODEL_FAILED"}


