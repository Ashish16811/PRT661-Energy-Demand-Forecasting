@dataclass(frozen=True)
class SequenceSpec:
    """Lookback 336 = 7 days (primary GRU). 672 = 14 days is SENSITIVITY_ONLY (GRU_L672)."""
    lookback: int = edp.GRU_LOOKBACK
    stride: int = edp.GRU_PARAMETERS["full"]["train_stride"]
    model_name: str = "GRU"

    @classmethod
    def primary(cls, quick: bool = False) -> "SequenceSpec":
        return cls(edp.GRU_LOOKBACK, edp.GRU_PARAMETERS["quick" if quick else "full"]["train_stride"], "GRU")

    @classmethod
    def sensitivity(cls, quick: bool = False) -> "SequenceSpec":
        return cls(edp.GRU_SENSITIVITY_LOOKBACK, edp.GRU_PARAMETERS["quick" if quick else "full"]["train_stride"],
                   edp.SENSITIVITY_MODEL)

    @property
    def competes_in_selection(self) -> bool:
        return self.model_name in edp.MODEL_REGISTRY


ENCODER_CHANNELS = ["demand_scaled"] + list(edp.GRU_ENCODER_CALENDAR)
DECODER_FEATURES = list(edp.GRU_DECODER_FEATURES)


